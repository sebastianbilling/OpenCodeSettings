// Writes generated/facts/<repo>.md: everything scripts can tell about one repo,
// in a form an AI (or a person) can read in a few minutes. No AI is involved here.
import path from 'node:path';
import { GENERATED, REPOS_DIR, git, num, pct, today, writeText } from './common.mjs';

const UNINTERESTING_PLUGINS = /HelpTasks|SoftwareReporting|BuildInit|WrapperPlugin|LifecycleBase|\.BasePlugin$|JvmEcosystem|ReportingBase|JvmToolchains|JavaBasePlugin|TestSuiteBase|JvmTestSuite|KotlinScript|ProjectReportsPlugin|JvmToolchainManagement/;

export function factsFile(repo) {
  return path.join(GENERATED, 'facts', `${repo}.md`);
}

function gitFacts(repo) {
  const dir = path.join(REPOS_DIR, repo);
  const sha = git(dir, ['rev-parse', '--short', 'HEAD']);
  if (!sha) return null;
  const since = '12 months ago';
  const files = git(dir, ['log', `--since=${since}`, '--name-only', '--format=']).split(/\r?\n/).filter(Boolean);
  const folders = {};
  for (const f of files) {
    const d = path.posix.dirname(f.replace(/\\/g, '/'));
    folders[d] = (folders[d] || 0) + 1;
  }
  return {
    sha,
    branch: git(dir, ['rev-parse', '--abbrev-ref', 'HEAD']),
    lastCommit: git(dir, ['log', '-1', '--format=%cs']),
    commitsYear: git(dir, ['rev-list', '--count', `--since=${since}`, 'HEAD']) || '0',
    authorsYear: git(dir, ['shortlog', '-sn', `--since=${since}`, 'HEAD']).split(/\r?\n/).filter(Boolean).length,
    topFolders: Object.entries(folders).sort((a, b) => b[1] - a[1]).slice(0, 8),
    subjects: git(dir, ['log', '-12', '--format=%s']).split(/\r?\n/).filter(Boolean)
  };
}

const list = (arr, fmt, n = 12) => arr.slice(0, n).map(fmt).join(' · ') || '(none)';

export function writeFacts(repo, g) {
  const s = g.stats[repo];
  const d = g.deps[repo] || { projects: [] };
  const gi = gitFacts(repo);
  const L = [];
  L.push(`# Facts: ${repo}`, '');
  L.push(`Generated by tools/refresh.mjs on ${today()}${gi ? ` from commit ${gi.sha} (branch ${gi.branch})` : ''}. Every number here was counted by a script, not guessed by an AI.`, '');

  // ---- size and build
  L.push('## Size and build', '');
  if (s) L.push(`- Java files: ${num(s.files)} (main ${num(s.mainFiles)}, test ${num(s.testFiles)}); lines: ${num(s.lines)} (main ${num(s.mainLines)}, test ${num(s.testLines)})`);
  else L.push('- No Java index for this repo yet (run tools/refresh.mjs).');
  if (s?.parseErrorFiles) L.push(`- ${s.parseErrorFiles} files have syntax the parser did not fully understand.`);
  const projects = d.projects || [];
  const modules = projects.filter(p => p.path !== ':').map(p => (p.build ? `${p.build} ${p.path}` : p.path));
  const builds = d.builds?.length ? d.builds
    : (['maven-static', 'none'].includes(d.source) ? [] : [{ dir: '', source: d.source, gradleVersion: d.gradleVersion, wrapperDir: d.wrapper ? '' : null }]);
  const win = p => p.replace(/\//g, '\\');
  const testCmd = b => {
    const where = b.dir ? `repos\\${repo}\\${win(b.dir)}` : `repos\\${repo}`;
    if (b.wrapperDir === null || b.wrapperDir === undefined) return { runIn: where, cmd: 'gradle' };
    if (b.wrapperDir === b.dir) return { runIn: where, cmd: '.\\gradlew.bat' };
    const wdir = b.wrapperDir ? `repos\\${repo}\\${win(b.wrapperDir)}` : `repos\\${repo}`;
    return { runIn: wdir, cmd: `.\\gradlew.bat -p ${win(path.posix.relative(b.wrapperDir, b.dir))}` };
  };
  const how = b => (b.source === 'gradle' ? `asked Gradle ${b.gradleVersion || ''}`.trim() : `read the build files as text${b.error ? ' (Gradle could not run here)' : ''}`);
  if (d.source === 'maven-static') L.push('- Build: Maven; facts below: read pom.xml');
  else if (!builds.length) L.push('- Build: no Gradle or Maven build found');
  else if (builds.length === 1) {
    const b = builds[0], t = testCmd(b);
    L.push(`- Build: Gradle${b.gradleVersion ? ' ' + b.gradleVersion : ''}${b.wrapperDir !== null && b.wrapperDir !== undefined ? ' (wrapper in repo)' : ''}${b.dir ? ` in ${b.dir}/` : ''}; facts below: ${how(b)}`);
    if (modules.length) L.push(`- Modules (${modules.length}): ${modules.slice(0, 30).join(', ')}${modules.length > 30 ? ', ...' : ''}`);
    L.push(`- Likely test command, run in ${t.runIn} (PowerShell): \`${t.cmd} test\``);
    L.push(`- One test class: \`${t.cmd} ${modules.length ? ':<module>:' : ''}test --tests "<package.ClassName>"\``);
  } else {
    L.push(`- Gradle builds: ${builds.length} separate builds in this repo, each in its own folder with its own test command:`);
    for (const b of builds) {
      const t = testCmd(b);
      const mods = projects.filter(p => p.build === b.dir && p.path !== ':').map(p => p.path);
      L.push(`    - ${b.dir || '(repo root)'}: ${how(b)}.${mods.length ? ` Modules (${mods.length}): ${mods.slice(0, 15).join(', ')}${mods.length > 15 ? ', ...' : ''}.` : ''} Tests: run in ${t.runIn}: \`${t.cmd} test\``);
    }
    L.push('- One test class: add `--tests "<package.ClassName>"` to the test command of the build that holds the class.');
  }
  const javaLevels = [...new Set(projects.map(p => p.javaVersion).filter(Boolean))];
  if (javaLevels.length) {
    const unsure = (d.buildFileHints || []).some(h => h.startsWith('Java level is not set'));
    L.push(`- Java language level: ${javaLevels.join(', ')}${unsure && d.source !== 'static' ? ' (as Gradle reports it; if the build never sets it, this is just the JDK Gradle ran on)' : ''}`);
  }
  if (s) L.push(`- Language features in use: lambdas in ${num(s.language.filesWithLambdas)} files, var in ${num(s.language.filesWithVar)}, records in ${num(s.language.filesWithRecords)}, switch expressions in ${num(s.language.filesWithSwitchExpressions)}`);
  const plugins = [...new Set(projects.flatMap(p => p.plugins || []).filter(p => !UNINTERESTING_PLUGINS.test(p))
    .map(p => (p.includes('.') && /[A-Z]/.test(p.split('.').pop()) ? p.split('.').pop() : p)))];
  if (plugins.length && d.source !== 'maven-static') L.push(`- Gradle plugins: ${plugins.slice(0, 15).join(', ')}`);
  for (const h of d.buildFileHints || []) L.push(`- Note: ${h}`);
  if (d.gradleError) L.push(`- Gradle error: ${String(d.gradleError).split('\n').filter(Boolean).slice(0, 4).join(' / ').slice(0, 400)}`);
  L.push('');

  // ---- dependencies
  L.push('## Dependencies', '');
  const uses = Object.entries(g.edges[repo] || {});
  L.push(`- Uses jars from: ${uses.length ? uses.map(([to, l]) => `${to} (${[...new Set(l.map(e => e.coord.split(':')[1] + ' ' + (e.version || '?')))].slice(0, 3).join(', ')})`).join(', ') : '(no other repo)'}`);
  L.push(`- Used by: ${g.usedBy[repo]?.length ? g.usedBy[repo].join(', ') : '(no other repo)'}`);
  if (s && Object.keys(s.usedByRepos || {}).length) L.push(`- Files in other repos that use this repo's classes: ${Object.entries(s.usedByRepos).map(([r, n]) => `${r} ${n}`).join(', ')}`);
  if (g.localJars[repo]?.length) L.push(`- Jar files kept inside the repo: ${g.localJars[repo].slice(0, 10).join(', ')}`);
  const external = {};
  for (const p of projects) for (const dep of p.dependencies || []) {
    if (dep.type !== 'module' || !dep.group) continue;
    const key = `${dep.group}:${dep.name}`;
    if (Object.values(g.edges[repo] || {}).some(l => l.some(e => e.coord === key))) continue;
    external[key] = dep.version || external[key] || '';
  }
  const ext = Object.entries(external).sort();
  if (ext.length) L.push(`- Other libraries declared (${ext.length}): ${ext.slice(0, 40).map(([k, v]) => v ? `${k}:${v}` : k).join(', ')}${ext.length > 40 ? ', ...' : ''}`);
  L.push('');

  if (s) {
    // ---- structure
    L.push('## Code structure', '');
    L.push(`- Root package: ${s.rootPackage || '(mixed)'}`);
    L.push(`- Biggest packages (main code, files): ${list(s.packages, p => `${p.name} ${p.files}`, 15)}`);
    L.push(`- Type kinds: ${Object.entries(s.kinds).map(([k, v]) => `${k} ${v}`).join(', ')}`);
    L.push('');

    // ---- naming
    L.push('## Naming in main code', '');
    L.push(`- Most common name endings: ${list(s.suffixes, x => `${x.suffix} ${x.count} (e.g. ${x.example})`, 20)}`);
    const n = s.naming;
    L.push(`- Interfaces: ${n.interfaces}, of which ${n.interfacesStartingWithI} use an "I" prefix (IOrderService style). Classes ending in "Impl": ${n.classesEndingInImpl}. Abstract classes: ${n.abstractClasses}, of which ${n.abstractStartingWithAbstractOrBase} start with Abstract/Base.`);
    if (s.loggerFields.length) L.push(`- Logger fields (type and name): ${list(s.loggerFields, x => `"${x.field}" ${x.count}`, 6)}`);
    if (s.exceptions.custom) L.push(`- Own exception classes: ${s.exceptions.custom}; they extend: ${Object.entries(s.exceptions.extend).map(([k, v]) => `${k} ${v}`).join(', ')}`);
    L.push(`- Public classes with a Javadoc comment: ${s.javadoc.withJavadoc} of ${s.javadoc.publicTopLevelTypes} (${pct(s.javadoc.withJavadoc, s.javadoc.publicTopLevelTypes)})`);
    L.push('');

    // ---- frameworks
    L.push('## Frameworks and libraries in the code', '');
    L.push(`- Imported packages (files that import them): ${list(s.importGroups, x => `${x.prefix} ${x.files}`, 25)}`);
    L.push(`- Annotations in main code: ${list(s.annotations, x => `${x.name} ${x.count}`, 30)}`);
    L.push('');

    // ---- tests
    L.push('## Tests', '');
    L.push(`- Test class names end in: ${Object.entries(s.tests.classSuffix).map(([k, v]) => `${k} ${v}`).join(', ') || '(no tests found)'}`);
    L.push(`- Test method name styles: ${Object.entries(s.tests.methodStyles).map(([k, v]) => `${k} ${v}`).join(', ') || '(none)'}`);
    L.push(`- Test libraries (files importing them): ${Object.entries(s.tests.frameworks).map(([k, v]) => `${k} ${v}`).join(', ') || '(none)'}`);
    L.push(`- Annotations in test code: ${list(s.testAnnotations, x => `${x.name} ${x.count}`, 12)}`);
    L.push('');

    // ---- entry points and important types
    L.push('## Entry points', '');
    if (s.entryPoints.length) for (const e of s.entryPoints.slice(0, 12)) L.push(`- ${e.type} (${e.file}:${e.line}): ${e.why}`);
    else L.push('- None found (no main methods, servlets or *Application annotations). Probably a library.');
    L.push('');

    L.push('## Most used classes in this repo', '', 'Used = number of other files that refer to the class. These are usually the core concepts.', '');
    L.push('| Class | Kind | Used in files | File | Javadoc summary |', '| --- | --- | --- | --- | --- |');
    for (const t of s.coreTypes.slice(0, 20)) L.push(`| ${t.type.split('.').pop()} | ${t.kind} | ${t.usedByFiles} | ${t.file} | ${t.doc.replace(/\|/g, '/')} |`);
    L.push('');
    if (s.usedByOtherReposTypes.length) {
      L.push('## Classes other repos use most', '', 'This is in practice the public API of this repo. Changing these affects the repos listed under "Used by".', '');
      L.push('| Class | Files in other repos | File |', '| --- | --- | --- |');
      for (const t of s.usedByOtherReposTypes.slice(0, 15)) L.push(`| ${t.type} | ${t.usedByOtherRepoFiles} | ${t.file} |`);
      L.push('');
    }
    L.push('## Largest files', '', 'Read these in parts (offset and limit), never whole.', '');
    L.push(list(s.largestFiles, f => `${f.file} (${num(f.lines)} lines)`, 10), '');
  }

  // ---- git
  if (gi) {
    L.push('## Activity (from git)', '');
    L.push(`- Last commit: ${gi.lastCommit}. Commits in the last 12 months: ${gi.commitsYear}, by ${gi.authorsYear} people.`);
    if (gi.topFolders.length) L.push(`- Most changed folders in the last 12 months: ${gi.topFolders.map(([f, c]) => `${f} (${c})`).join(', ')}`);
    if (gi.subjects.length) {
      L.push('- Recent commit messages (shows the message style):');
      for (const sj of gi.subjects.slice(0, 10)) L.push(`    - ${sj.slice(0, 120)}`);
    }
    L.push('');
  }

  // ---- reading list for the cartographer
  if (s?.suggestedFiles?.length) {
    L.push('## Suggested files to read first', '');
    s.suggestedFiles.forEach((f, i) => L.push(`${i + 1}. repos/${repo}/${f.file} (${f.why})`));
    L.push('');
  }
  writeText(factsFile(repo), L.join('\n'));
  return gi;
}

/** generated/overview.md: a few lines per repo, so one file shows patterns across all repos.
 *  Used by /draft-conventions and /draft-glossary. */
export function writeOverview(g) {
  const L = ['# Overview of all repos', '',
    `Generated by tools/refresh.mjs on ${today()}. Counts from scripts. One block per repo; details in generated/facts/<repo>.md.`, ''];
  for (const r of g.repos) {
    const s = g.stats[r];
    if (!s) continue;
    const d = g.deps[r] || { projects: [] };
    const java = [...new Set((d.projects || []).map(p => p.javaVersion).filter(Boolean))].join(', ') || '?';
    L.push(`## ${r}`);
    L.push(`- Size: ${num(s.mainFiles)} main and ${num(s.testFiles)} test files. Java level ${java}. Lambdas in ${pct(s.language.filesWithLambdas, s.files)} of files.`);
    L.push(`- Name endings: ${s.suffixes.slice(0, 8).map(x => `${x.suffix} ${x.count}`).join(', ') || '(none)'}. I-prefixed interfaces ${s.naming.interfacesStartingWithI} of ${s.naming.interfaces}; Impl classes ${s.naming.classesEndingInImpl}.`);
    if (s.loggerFields.length) L.push(`- Logger fields: ${s.loggerFields.slice(0, 3).map(x => `"${x.field}" ${x.count}`).join(', ')}`);
    if (s.exceptions.custom) L.push(`- Own exceptions: ${s.exceptions.custom}, extending ${Object.entries(s.exceptions.extend).slice(0, 3).map(([k, v]) => `${k} ${v}`).join(', ')}`);
    L.push(`- Tests: classes end in ${Object.entries(s.tests.classSuffix).slice(0, 3).map(([k, v]) => `${k} ${v}`).join(', ') || '-'}; methods ${Object.entries(s.tests.methodStyles).slice(0, 3).map(([k, v]) => `${k} ${v}`).join(', ') || '-'}; libraries ${Object.entries(s.tests.frameworks).slice(0, 4).map(([k, v]) => `${k} ${v}`).join(', ') || '-'}`);
    L.push(`- Frameworks (files importing): ${s.importGroups.filter(x => !x.prefix.startsWith('java.')).slice(0, 8).map(x => `${x.prefix} ${x.files}`).join(', ')}`);
    L.push(`- Main classes: ${s.coreTypes.slice(0, 8).map(t => `${t.type.split('.').pop()} (${t.usedByFiles})${t.doc ? ': ' + t.doc.slice(0, 80) : ''}`).join('; ')}`);
    L.push('');
  }
  writeText(path.join(GENERATED, 'overview.md'), L.join('\n'));
}
